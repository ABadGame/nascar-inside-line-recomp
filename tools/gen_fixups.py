"""Turn ReXGlue 'target not in any function' errors into [functions] entries.

usage: python gen_fixups.py default.bin codegen.out fixups.toml

Appends to (or creates) fixups.toml, keeping earlier entries, so it can be
re-run after each codegen pass.

Rules, for each (target, from) pair:
  1. target and from in the same .pdata gap segment  -> the branch is inside one
     leaf function that ReXGlue split at an early blr; declare the whole segment.
  2. otherwise -> target is a real entry (thunk / leaf / trampoline); declare it
     from the target to the first terminator past its furthest forward branch.
A "gap segment" is the space between two .pdata functions, split on zero padding.
"""
import re, struct, sys, os
from bisect import bisect_right

BASE = 0x82000000
PDATA = (0x82232400, 0x822B3058)
img = open(sys.argv[1], "rb").read()
w = lambda a: struct.unpack_from(">I", img, a - BASE)[0]

funcs = []
for a in range(PDATA[0], PDATA[1], 8):
    b, p = w(a), w(a + 4)
    if b:
        funcs.append((b, ((p >> 8) & 0x3FFFFF) * 4))
funcs.sort()
starts = [f[0] for f in funcs]


def segment(a):
    i = bisect_right(starts, a) - 1
    lo = funcs[i][0] + funcs[i][1]
    hi = funcs[i + 1][0]
    if not (lo <= a < hi):
        return None
    s = a
    while s > lo and w(s - 4) != 0:
        s -= 4
    e = a
    while e < hi and w(e) != 0:
        e += 4
    return s, e


def branch_target(x, a):
    op = x >> 26
    if op == 18:
        li = x & 0x03FFFFFC
        if li & 0x02000000: li -= 0x04000000
        return (a + li) & 0xFFFFFFFF
    if op == 16:
        bd = x & 0xFFFC
        if bd & 0x8000: bd -= 0x10000
        return (a + bd) & 0xFFFFFFFF
    return None


def entry_extent(t, limit):
    furthest, a = t, t
    while a < limit:
        x = w(a)
        op = x >> 26
        bt = branch_target(x, a)
        if op == 16 and bt and t <= bt < limit:
            furthest = max(furthest, bt)
        terminator = x in (0x4E800020, 0x4E800420) or (op == 18 and not x & 1)
        if terminator and a >= furthest:
            return a + 4
        a += 4
    return limit


errs = re.findall(r"0x([0-9A-F]{8}) from 0x([0-9A-F]{8}): b", open(sys.argv[2], encoding="utf-8", errors="replace").read())
errs = sorted({(int(t, 16), int(f, 16)) for t, f in errs})

existing = {}
if os.path.exists(sys.argv[3]):
    for m in re.finditer(r'"0x([0-9A-F]+)" = \{ size = 0x([0-9A-F]+) \}\s*(#.*)?', open(sys.argv[3]).read()):
        existing[int(m[1], 16)] = (int(m[2], 16), (m[3] or "").lstrip("# "))

added = 0
for t, f in errs:
    seg = segment(t)
    if seg is None:
        print(f"  ?? 0x{t:08X}: not in a .pdata gap, needs a manual look")
        continue
    if seg[0] <= f < seg[1]:
        start, end, why = seg[0], seg[1], f"leaf fn split at early blr (b from 0x{f:08X})"
    else:
        start, end, why = t, entry_extent(t, seg[1]), f"entry reached by b from 0x{f:08X}"
    if start not in existing:
        existing[start] = (end - start, why)
        added += 1
        print(f"  0x{start:08X} size 0x{end - start:X}  {why}")

with open(sys.argv[3], "w") as o:
    o.write("# Function entries for code ReXGlue left outside any function.\n")
    o.write("# Generated by tools/gen_fixups.py from codegen 'target not in any function' errors.\n\n")
    o.write("[functions]\n")
    for a in sorted(existing):
        size, why = existing[a]
        o.write(f'"0x{a:X}" = {{ size = 0x{size:X} }}  # {why}\n')
print(f"{added} added, {len(existing)} total -> {sys.argv[3]}")
